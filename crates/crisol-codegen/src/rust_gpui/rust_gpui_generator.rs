use crisol_catalog::WidgetCatalog;
use crisol_catalog::validation::CatalogValidator;
use crisol_model::document::FormDocument;

use super::constructor_writer::ConstructorWriter;
use super::element_writer::ElementWriter;
use super::event_binding_collector::EventBindingCollector;
use super::events_trait_writer::EventsTraitWriter;
use super::generation_context::GenerationContext;
use crate::writing::{CodeWriter, NameConverter};
use crate::{CodeGenerator, CodegenError, CodegenResult, CodegenSettings, GeneratedFile};

/// Generates `<form>.generated.rs`: the events trait, the form struct and its `Render`.
pub struct RustGpuiGenerator<'catalog> {
    catalog: &'catalog WidgetCatalog,
    settings: CodegenSettings,
}

impl<'catalog> RustGpuiGenerator<'catalog> {
    pub fn new(catalog: &'catalog WidgetCatalog, settings: CodegenSettings) -> Self {
        Self { catalog, settings }
    }

    /// `<module>.generated.rs`, for the module named after the form file.
    pub fn file_name_for(&self, module: &str) -> String {
        format!("{module}{}", self.settings.generated_suffix)
    }

    pub fn file_name(&self, document: &FormDocument) -> String {
        format!(
            "{}{}",
            NameConverter::snake_case(document.form().name.as_str()),
            self.settings.generated_suffix
        )
    }

    fn write_header(&self, writer: &mut CodeWriter) {
        writer.line("// Generated by Crisol. Do not edit: this file is rewritten on every save.");
        writer.line("#![allow(unused_imports, clippy::all, clippy::pedantic)]");
        writer.blank();
        writer.line(&format!("use {}::prelude::*;", self.settings.runtime_crate));
        writer.line("use gpui::{Context, Entity, IntoElement, Render, Window, prelude::*};");
        writer.blank();
    }
}

impl CodeGenerator for RustGpuiGenerator<'_> {
    fn generate(&self, document: &FormDocument) -> CodegenResult<GeneratedFile> {
        let mut errors = 0;
        for diagnostic in CatalogValidator::new(self.catalog).validate(document) {
            if diagnostic.is_error() {
                errors += 1;
            }
        }
        if errors > 0 {
            return Err(CodegenError::InvalidDocument(errors));
        }
        let bindings = EventBindingCollector::new(document, self.catalog).collect();
        let context = GenerationContext {
            document,
            catalog: self.catalog,
            bindings: &bindings,
        };
        let mut writer = CodeWriter::new(self.settings.indent_width);
        self.write_header(&mut writer);
        EventsTraitWriter::new(document, &bindings).write(&mut writer);
        writer.blank();
        let constructor = ConstructorWriter::new(&context);
        constructor.write_struct(&mut writer);
        writer.blank();
        constructor.write_constructor(&mut writer);
        writer.blank();
        ElementWriter::new(&context).write_render(&mut writer);
        Ok(GeneratedFile {
            file_name: self.file_name(document),
            content: writer.finish(),
        })
    }
}
